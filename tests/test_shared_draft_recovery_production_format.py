"""Recovery reads a completed Shared Draft room in the format production actually stores.

Hosted build 9bc266f refused the owner's room DA9E78 with "pick N has no player" for all four picks.
A Shared Draft pick is the drafted player's pool row (live_draft_make_pick copies it), so the room
stores the name as "fullName" and the id as "playerID", never "Player". The earlier tests built their
boards by hand with both keys, so they could not see the gap. These tests use rooms produced by the
real writers: a sanitized fixture generated by them, and a room built by them during the test.
"""

from __future__ import annotations

import copy
import json
import tempfile
import unittest
from pathlib import Path
from unittest import mock

from draft_archive_state import list_draft_archives
from draft_room_shared_state import LocalFileSharedRoomStore
from fantasy_league_context import save_live_draft_league_context
from shared_draft_recovery import (
    ROOM_KEY_FIELD,
    list_recoverable_rooms,
    load_recovery_preview,
    recover_completed_shared_draft,
)

CODE = "DA9E78"
FIXTURE = Path(__file__).resolve().parent / "fixtures" / "shared_draft_room_production_format.json"
# The owner's exported CSV: pick order, team, player id, name.
EXPECTED = [
    (1, "Danny", "olsonma02", "Matt Olson"),
    (2, "Barry", "raleica01", "Cal Raleigh"),
    (3, "Barry", "alonspe01", "Pete Alonso"),
    (4, "Danny", "perezsa02", "Salvador Perez"),
]


def production_document() -> dict:
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def signed_in(account: str) -> dict:
    return {"_suite_auth_session": True, "_suite_auth_user_id": f"uuid-{account}",
            "_suite_cloud_user_id": f"uuid-{account}", "_suite_auth_external_id": account,
            "_suite_owned_workspace_id": account, "_suite_active_workspace_id": account}


def build_room_with_the_real_writers(code: str = "NEW001") -> dict:
    """A brand-new completed room: the real pick engine and the real shared-document serializer."""
    import pandas as pd

    from draft_room_shared_state import shared_room_document
    from live_draft_pick_engine import live_draft_make_pick

    clubs = {"olsonma02": ("1B", "ATL"), "raleica01": ("C", "SEA"), "alonspe01": ("1B", "NYM"), "perezsa02": ("C", "KC")}
    pool = pd.DataFrame([
        {"playerID": pid, "fullName": name, "Primary Position": clubs[pid][0], "Team": clubs[pid][1],
         "Eligible Positions": clubs[pid][0], "Expected Fantasy Value": 80.0 - n, "Model Rank": n, "Market Rank": n,
         "Fantasy Edge": 0.0}
        for n, _team, pid, name in EXPECTED
    ])
    room = {
        "status": "in_progress", "current_pick_index": 0, "teams": ["Danny", "Barry"],
        "config": {"league_name": "My Fantasy League", "fantasy_format": "5x5 Roto", "scoring_type": "5x5 Roto",
                   "num_teams": 2, "picks_per_team": 2, "slots": {"C": 1, "1B": 1}, "teams": ["Danny", "Barry"],
                   "timer_seconds": 60},
        "pick_order": [{"Pick": n, "Round": (n + 1) // 2, "Team": team} for n, team, _pid, _name in EXPECTED],
        "draft_board": [], "rosters": {"Danny": [], "Barry": []}, "drafted_player_ids": [], "pool": pool,
    }
    for _n, _team, pid, _name in EXPECTED:
        ok, message = live_draft_make_pick(room, pool[pool["playerID"] == pid].iloc[0].to_dict(), "Manual pick",
                                           enrich_pick_context=False)
        assert ok, message
    doc = shared_room_document(room_code=code, host_participant_id="uuid-danny", live_room=room, revision=11)
    doc["host_user_id"] = "uuid-danny"
    doc["participants"] = production_document()["participants"]
    return doc


class _Case(unittest.TestCase):
    def setUp(self) -> None:
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.root = Path(tmp.name)
        self.store = LocalFileSharedRoomStore(root=self.root)
        self.write_room(production_document())
        self.saves: list[str] = []
        save = mock.patch("baseball_persistent_state.force_save_baseball_state", side_effect=self._record_save)
        save.start()
        self.addCleanup(save.stop)

    def _record_save(self, st, reason="", **_kw):
        self.saves.append(str(reason))
        return True

    def write_room(self, doc: dict, code: str = CODE) -> None:
        (self.root / f"{code}.json").write_text(json.dumps(doc), encoding="utf-8")

    def room_bytes(self, code: str = CODE) -> bytes:
        return (self.root / f"{code}.json").read_bytes()

    def preview(self, session: dict, code: str = CODE) -> dict:
        return load_recovery_preview(session, code, store=self.store)

    def recover(self, session: dict, code: str = CODE) -> dict:
        preview = self.preview(session, code)
        st = mock.MagicMock()
        st.session_state = session
        with mock.patch("suite_cloud_state._streamlit_session", return_value=session):
            return recover_completed_shared_draft(st, session, code, confirmed=True,
                                                  expected_revision=preview.get("revision", 0), store=self.store)


class StoredFormatTests(_Case):
    def test_the_fixture_is_the_production_format(self) -> None:
        board = production_document()["room"]["draft_board"]
        self.assertEqual(len(board), 4)
        for pick in board:
            self.assertNotIn("Player", pick)  # what the hosted refusal tripped on
            self.assertTrue(pick["fullName"] and pick["playerID"] and pick["Fantasy Team"])
        self.assertEqual(build_room_with_the_real_writers()["room"]["draft_board"][0].keys(), board[0].keys())

    def test_all_four_picks_are_recognised_in_order_with_team_and_id(self) -> None:
        preview = self.preview(signed_in("danny"))
        self.assertTrue(preview["ok"], preview["problems"])
        self.assertEqual(preview["problems"], [])
        self.assertEqual(preview["missing"], [])
        self.assertEqual([(p["pick"], p["team"], p["player_id"], p["player"]) for p in preview["picks"]], EXPECTED)
        self.assertEqual((preview["status"], preview["revision"], preview["team"], preview["role"]),
                         ("complete", 11, "Danny", "commissioner"))
        self.assertEqual(preview["settings"]["fantasy_format"], "5x5 Roto")
        self.assertEqual(preview["settings"]["roster_slots"], {"C": 1, "1B": 1})

    def test_no_duplicate_or_missing_picks(self) -> None:
        ids = [p["player_id"] for p in self.preview(signed_in("danny"))["picks"]]
        self.assertEqual(len(ids), len(set(ids)))
        self.assertEqual(sorted(ids), sorted(pid for _n, _t, pid, _name in EXPECTED))


class ReconstructionTests(_Case):
    def test_commissioner_recovery_rebuilds_teams_rosters_and_order(self) -> None:
        session = signed_in("danny")
        out = self.recover(session)
        self.assertTrue(out["ok"], out)
        entry = next(e for e in list_draft_archives(session) if e["draft_id"] == out["draft_id"])
        self.assertEqual((entry["team_name"], entry[ROOM_KEY_FIELD], entry["draft_id"]), ("Danny", CODE, "room-da9e78"))
        self.assertEqual([(p["player_id"], p["player_name"]) for p in entry["players"]],
                         [("olsonma02", "Matt Olson"), ("perezsa02", "Salvador Perez")])
        self.assertEqual([(r["Pick"], r["Fantasy Team"], r["playerID"], r["fullName"]) for r in entry["draft_board"]],
                         EXPECTED)
        rosters = {team: [r["player_id"] for r in (rows.get("players") if isinstance(rows, dict) else rows)]
                   for team, rows in entry["league_rosters"].items()}
        self.assertEqual(rosters, {"Danny": ["olsonma02", "perezsa02"], "Barry": ["raleica01", "alonspe01"]})
        self.assertEqual(self.saves, ["shared_draft_recovered"])

    def test_participant_recovery_keeps_that_participants_team(self) -> None:
        session = signed_in("barry")
        out = self.recover(session)
        self.assertTrue(out["ok"], out)
        entry = list_draft_archives(session)[0]
        self.assertEqual(entry["team_name"], "Barry")
        self.assertEqual([p["player_id"] for p in entry["players"]], ["raleica01", "alonspe01"])

    def test_a_newly_created_room_from_the_real_writers_recovers(self) -> None:
        self.write_room(build_room_with_the_real_writers("NEW001"), "NEW001")
        session = signed_in("danny")
        preview = self.preview(session, "NEW001")
        self.assertTrue(preview["ok"], preview["problems"])
        self.assertEqual([(p["pick"], p["team"], p["player_id"], p["player"]) for p in preview["picks"]], EXPECTED)
        self.assertTrue(self.recover(session, "NEW001")["ok"])

    def test_an_older_room_with_player_names_and_a_legacy_live_room_key_still_recovers(self) -> None:
        doc = production_document()
        legacy = doc.pop("room")
        for pick in legacy["draft_board"]:
            pick["Player"] = pick.pop("fullName")
        doc["live_room"] = legacy
        self.write_room(doc)
        preview = self.preview(signed_in("danny"))
        self.assertTrue(preview["ok"], preview["problems"])
        self.assertEqual([p["player"] for p in preview["picks"]], [name for *_x, name in EXPECTED])


class RejectionTests(_Case):
    def _with_board(self, change) -> dict:
        doc = production_document()
        change(doc["room"]["draft_board"])
        self.write_room(doc)
        return self.preview(signed_in("danny"))

    def test_a_pick_with_no_stored_name_is_still_refused_never_looked_up(self) -> None:
        preview = self._with_board(lambda board: board[1].pop("fullName"))
        self.assertFalse(preview["ok"])
        self.assertIn("pick 2 has no player", preview["problems"])
        self.assertEqual(preview["picks"][1]["player"], "")  # shown as blank, not filled from the id
        out = self.recover(signed_in("danny"))
        self.assertFalse(out["ok"])
        self.assertEqual(list_draft_archives(signed_in("danny")), [])

    def test_blank_or_nan_names_are_refused(self) -> None:
        def blank(board):
            board[0]["fullName"] = "  "
            board[3]["fullName"] = "nan"
        problems = self._with_board(blank)["problems"]
        self.assertIn("pick 1 has no player", problems)
        self.assertIn("pick 4 has no player", problems)

    def test_the_same_player_id_twice_is_refused(self) -> None:
        def dup(board):
            board[3]["playerID"] = board[0]["playerID"]
        self.assertIn("Salvador Perez was picked twice", self._with_board(dup)["problems"])

    def test_two_different_players_who_share_a_name_are_not_a_duplicate(self) -> None:
        def same_name(board):
            board[3]["fullName"] = board[0]["fullName"]
        preview = self._with_board(same_name)
        self.assertTrue(preview["ok"], preview["problems"])

    def test_a_missing_or_blank_player_id_is_refused_never_looked_up(self) -> None:
        def no_ids(board):
            board[2].pop("playerID")
            board[0]["playerID"] = "nan"
        preview = self._with_board(no_ids)
        self.assertFalse(preview["ok"])
        self.assertIn("pick 3 (Pete Alonso) has no player id", preview["problems"])
        self.assertIn("pick 1 (Matt Olson) has no player id", preview["problems"])
        self.assertEqual(preview["picks"][2]["player_id"], "")  # shown as blank, not filled from the name
        self.assertFalse(self.recover(signed_in("danny"))["ok"])
        self.assertEqual(list_draft_archives(signed_in("danny")), [])


class SafetyTests(_Case):
    def test_an_account_without_a_seat_sees_nothing_and_changes_nothing(self) -> None:
        before = self.room_bytes()
        stranger = signed_in("mallory")
        self.assertEqual(list_recoverable_rooms(stranger, store=self.store), [])
        self.assertFalse(self.preview(stranger)["ok"])
        self.assertFalse(self.recover(stranger)["ok"])
        self.assertEqual(list_draft_archives(stranger), [])
        self.assertEqual(self.room_bytes(), before)
        self.assertEqual(self.saves, [])

    def test_the_room_is_never_written_and_unrelated_entries_are_kept(self) -> None:
        before = self.room_bytes()
        session = signed_in("danny")
        other = copy.deepcopy(production_document()["room"])
        other["config"]["league_name"] = "Another League"
        other["draft_board"] = other["draft_board"][:2]
        other["rosters"] = {"Danny": other["rosters"]["Danny"][:1], "Barry": other["rosters"]["Barry"][:1]}
        save_live_draft_league_context(session, other, my_team_name="Danny", draft_name="Unrelated", save_only=True)
        unrelated = copy.deepcopy(list_draft_archives(session))
        with mock.patch.object(LocalFileSharedRoomStore, "save") as room_save:
            out = self.recover(session)
        self.assertTrue(out["ok"], out)
        room_save.assert_not_called()
        self.assertEqual(self.room_bytes(), before)
        kept = [e for e in list_draft_archives(session) if e["draft_id"] == unrelated[0]["draft_id"]]
        self.assertEqual(kept, unrelated)
        self.assertEqual(len(list_draft_archives(session)), 2)


class LibraryPanelTests(_Case):
    def test_the_library_panel_previews_the_production_room_without_errors(self) -> None:
        from streamlit.testing.v1 import AppTest

        app = Path(__file__).resolve().parent / "fixtures" / "library_recovery_app.py"
        at = AppTest.from_file(str(app), default_timeout=120)
        for key, value in signed_in("danny").items():
            at.session_state[key] = value
        at.session_state["_fx_room_root"] = str(self.root)
        with mock.patch.dict("os.environ", {"SUITE_AUTH_ENABLED": "1"}):
            at.run()
            at.button(key="sdr_find").click().run()
            at.button(key="sdr_preview").click().run()
            self.assertFalse(at.exception, [str(e.value)[:300] for e in at.exception])
            errors = [str(e.value) for e in at.error]
            self.assertFalse([e for e in errors if "Can't recover" in e], errors)
            shown = str([d.value for d in at.dataframe])
            for _n, _team, pid, name in EXPECTED:
                self.assertIn(name, shown)
                self.assertIn(pid, shown)
            self.assertTrue(at.checkbox(key="sdr_confirm"))  # the confirm step is offered


